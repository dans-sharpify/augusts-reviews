"""Generate the two birch-forest layers for the film's opening chapter.

Seeded, so the output is identical on every rebuild. Emits plain <path> fills
(no strokes): a stroked path under a CSS transform re-rasterises the vector on
every frame, and these layers translate the whole way through chapter one.
"""
import random, pathlib

OUT = pathlib.Path(__file__).resolve().parent / "forest.svg"
W, H = 1600, 1000


def trunk(x, w, lean, seed):
    """One tapered birch, as a closed filled path plus a few bark scars."""
    r = random.Random(seed)
    top_w = w * r.uniform(0.55, 0.78)
    xb = x + lean
    d = (f"M{x - w / 2:.1f},{H} "
         f"C{x - w / 2 + r.uniform(-4, 4):.1f},{H * 0.62:.1f} "
         f"{xb - top_w / 2 + r.uniform(-5, 5):.1f},{H * 0.3:.1f} "
         f"{xb - top_w / 2:.1f},-40 "
         f"L{xb + top_w / 2:.1f},-40 "
         f"C{xb + top_w / 2 + r.uniform(-5, 5):.1f},{H * 0.3:.1f} "
         f"{x + w / 2 + r.uniform(-4, 4):.1f},{H * 0.62:.1f} "
         f"{x + w / 2:.1f},{H} Z")
    marks = []
    y = r.uniform(60, 200)
    while y < H - 40:
        mw = w * r.uniform(0.22, 0.5)
        mh = r.uniform(2.5, 6)
        mx = x + lean * (1 - y / H) + r.uniform(-w * 0.18, w * 0.18)
        marks.append(f'<rect x="{mx - mw / 2:.1f}" y="{y:.1f}" width="{mw:.1f}" '
                     f'height="{mh:.1f}" rx="{mh / 2:.1f}"/>')
        y += r.uniform(70, 190)
    return d, marks


def layer(n, seed, xw, alpha_trunk, alpha_mark, spread):
    r = random.Random(seed)
    paths, marks = [], []
    slot = W / n
    for i in range(n):
        x = slot * i + slot * r.uniform(0.15, 0.85)
        w = xw * r.uniform(0.7, 1.35)
        d, mk = trunk(x, w, r.uniform(-spread, spread), seed * 100 + i)
        paths.append(f'<path d="{d}"/>')
        marks += mk
    return (f'<g fill="#EDE6D6" fill-opacity="{alpha_trunk}">' + "".join(paths) + "</g>"
            f'<g fill="#12140E" fill-opacity="{alpha_mark}">' + "".join(marks) + "</g>")


far = layer(14, 7, 16, 0.13, 0.30, 10)
near = layer(6, 21, 46, 0.22, 0.42, 22)

svg = f"""<!-- generated by build/make-forest.py — do not hand-edit -->
<svg class="forest forest--far" viewBox="0 0 {W} {H}" preserveAspectRatio="xMidYMid slice" aria-hidden="true">{far}</svg>
<svg class="forest forest--near" viewBox="0 0 {W} {H}" preserveAspectRatio="xMidYMid slice" aria-hidden="true">{near}</svg>
"""
OUT.write_text(svg, encoding="utf-8")
print(f"{OUT}  {len(svg) // 1024} KB")
